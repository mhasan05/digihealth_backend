import os
import uuid
from django.db import models
from django.conf import settings


class FieldStaff(models.Model):
    """A field worker who collects prescriptions with the mobile app.

    Managed centrally by admins, so there is no hospital link.
    """
    STATUS_CHOICES = [
        ('Active', 'Active'),
        ('Inactive', 'Inactive'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.OneToOneField(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='field_staff_profile')
    area = models.CharField(max_length=200, blank=True, default='')
    status = models.CharField(max_length=10, choices=STATUS_CHOICES, default='Active')
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='created_field_staff',
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'field_collection_field_staff'
        ordering = ['-created_at']

    def __str__(self):
        return f"Field staff: {self.user.name}"


class FieldPrescription(models.Model):
    """A prescription collected in the field for a phone number.

    `patient` stays empty until someone has an account on `phone`; only then
    do the patient and doctors see it (see services.link_field_prescriptions).
    """
    STATUS_CHOICES = [
        ('unclaimed', 'Unclaimed'),
        ('claimed', 'Claimed'),
        ('disputed', 'Disputed'),
    ]
    GENDER_CHOICES = [
        ('Male', 'Male'),
        ('Female', 'Female'),
        ('Other', 'Other'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    # Normalized with core.utils.normalize_bd_phone — matched against User.phone.
    phone = models.CharField(max_length=20, db_index=True)
    patient_name = models.CharField(max_length=200, blank=True, default='')
    age = models.IntegerField(null=True, blank=True)
    gender = models.CharField(max_length=10, choices=GENDER_CHOICES, blank=True, default='')
    notes = models.TextField(blank=True, default='')
    consent_given = models.BooleanField(default=False)
    collected_by = models.ForeignKey(
        FieldStaff, on_delete=models.SET_NULL, null=True, related_name='prescriptions',
    )
    # Generated by the app per collection, so a retried upload doesn't duplicate.
    client_id = models.UUIDField(null=True, blank=True, unique=True)
    patient = models.ForeignKey(
        'patients.Patient', on_delete=models.SET_NULL, null=True, blank=True,
        related_name='field_prescriptions',
    )
    status = models.CharField(max_length=10, choices=STATUS_CHOICES, default='unclaimed')
    collected_at = models.DateTimeField(auto_now_add=True)
    claimed_at = models.DateTimeField(null=True, blank=True)
    dispute_reason = models.TextField(blank=True, default='')

    class Meta:
        db_table = 'field_collection_prescription'
        ordering = ['-collected_at']

    def __str__(self):
        return f"Field prescription for {self.phone} ({self.status})"


def field_prescription_upload_path(instance, filename):
    ext = os.path.splitext(filename)[1].lower() or '.jpg'
    rx = instance.prescription
    return f'field_rx/{rx.phone}/{rx.id}/{uuid.uuid4().hex}{ext}'


class FieldPrescriptionImage(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    prescription = models.ForeignKey(FieldPrescription, on_delete=models.CASCADE, related_name='images')
    file = models.FileField(upload_to=field_prescription_upload_path)
    page_no = models.PositiveIntegerField(default=1)
    size = models.BigIntegerField(default=0)
    content_type = models.CharField(max_length=100, blank=True, default='')
    uploaded_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'field_collection_prescription_image'
        ordering = ['page_no']

    def __str__(self):
        return f"Page {self.page_no} of {self.prescription_id}"
